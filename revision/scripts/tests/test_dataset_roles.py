# Non-run resources (issue #66, author decision 2026-09-03: declare them in the builder)
# ----------------------------------------------------------------------------------------------

def test_declared_resources_are_emitted_with_their_recorded_checksums():
    """The manifest is generated by scanning the evidence tree per sequencing run. A protein FASTA
    is not a run, is not in that tree, and has no genotype or instrument — so it can only get in by
    being declared. Hand-editing the TSV does not survive the next regeneration."""
    rows = list(dr.rows_for_resources())
    by_run = {r["run"]: r for r in rows}

    odb = by_run["odb12_Viridiplantae.filtered.fa.gz"]
    assert odb["local_fa_md5"] == "453cb32b02e0799950d7d5f4de5f62ac"
    assert odb["role"] == "c2_training_eligible"
    assert odb["data_type"] == "protein_resource"

    sp = by_run["uniprot_sprot_plants.dat.gz"]
    assert sp["local_fa_md5"] == "552089d0642b6c17f3486140a73a0163"
    assert sp["role"] == "sensitivity_set"          # the role added for A30 in this same issue set
    assert sp["data_type"] == "sensitivity_resource"


def test_declared_resources_pass_validation():
    """They must satisfy the same checks as scanned rows: a role in ROLES, a species, a checksum."""
    rows = list(dr.rows_for_resources())
    assert rows, "no resources declared"
    v = dr.validate(rows)
    assert not [x for x in v if "invalid role" in x or "no species" in x or "no checksum" in x], v


def test_build_includes_the_declared_resources(tmp_path):
    """build() must emit them alongside the scanned rows, or the manifest regenerates without them."""
    (tmp_path / "est").mkdir()
    rows = dr.build(str(tmp_path))
    runs = {r["run"] for r in rows}
    assert "odb12_Viridiplantae.filtered.fa.gz" in runs
    assert "uniprot_sprot_plants.dat.gz" in runs


